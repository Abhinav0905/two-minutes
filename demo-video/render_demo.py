def run(args):
    completed = subprocess.run([FFMPEG, "-hide_banner", "-loglevel", "error", *args], capture_output=True, text=True)
    if completed.returncode:
        raise RuntimeError(completed.stderr[-5000:])


def render_scene(item):
    index, scene = item
    pieces = []
    for n, (name, start, end, duration) in enumerate(EDITS[scene["id"]]):
        target = OUT / f"{scene['id']}-{n}.mp4"
        # Preserve the complete native frame, including the lid and front knob.
        run(["-ss", str(start), "-i", str(RAW / name), "-an", "-vf",
             f"trim=duration={end-start},setpts=(PTS-STARTPTS)*{duration/(end-start)},fps={FPS},scale=1140:1106:force_original_aspect_ratio=decrease,pad=1140:1106:(ow-iw)/2:(oh-ih)/2:color=0x060c10,setsar=1,tpad=stop_mode=clone:stop_duration=0.1",
             "-t", str(duration), "-c:v", "libx264", "-threads", "3", "-preset", "veryfast", "-crf", "18", "-pix_fmt", "yuv420p", "-y", str(target)])
        pieces.append(target)
    listing = OUT / f"{scene['id']}-concat.txt"
    listing.write_text("".join(f"file '{p.name}'\n" for p in pieces))
    background_path = background(scene, index)
    target = OUT / f"scene-{index:02}.mp4"
    run(["-loop", "1", "-framerate", str(FPS), "-i", str(background_path),
         "-f", "concat", "-safe", "0", "-i", str(listing), "-filter_complex",
         "[0:v][1:v]overlay=1330:149:shortest=1,format=yuv420p[v]", "-map", "[v]", "-an",
         "-t", str(scene["duration"]), "-c:v", "libx264", "-threads", "3", "-preset", "veryfast", "-crf", "19", "-y", str(target)])
    print("Rendered", scene["id"], flush=True)
    return target


def ass_time(ms):
    centiseconds = round(ms / 10)
    return f"{centiseconds//360000}:{centiseconds//6000%60:02}:{centiseconds//100%60:02}.{centiseconds%100:02}"


def make_captions():
    ass = """[Script Info]
ScriptType: v4.00+
PlayResX: 2560
PlayResY: 1440
WrapStyle: 2

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,Arial,46,&H00F5F7F7,&H00FFFFFF,&H0010191F,&H0010191F,0,0,0,0,100,100,0,0,1,0,0,2,160,160,47,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    for cue in captions:
        text = r"\N".join(textwrap.wrap(cue["text"], width=87))
        ass += f"Dialogue: 0,{ass_time(cue['startMs'])},{ass_time(cue['endMs'])},Default,,0,0,0,,{text}\n"
    target = OUT / "captions.ass"
    target.write_text(ass)
    return target


def cover():
    frame = OUT / "cover-native.png"
    run(["-ss", "7", "-i", str(RAW / "00-hero-fire.mp4"), "-frames:v", "1", "-y", str(frame)])
    image = Image.new("RGB", (1600, 900), BG)
    d = ImageDraw.Draw(image)
    d.rectangle((0, 0, 12, 900), fill=MINT)
    d.text((60, 62), "TWO MINUTES", font=font(34, True), fill=MINT)
    for y, line in [(183, "Know when"), (285, "to leave.")]:
        d.text((54, y), line, font=font(88, True), fill=INK)
    wrapped(d, "A kitchen fire practice drill for SPECS.", (60, 455), width=670, size=37, fill=MUTED)
    d.rounded_rectangle((60, 625, 696, 705), radius=12, fill="#24483e")
    d.text((86, 646), "Two scenarios. One decision.", font=font(35, True), fill=MINT)
    d.text((60, 816), "WORKING LENS STUDIO PREVIEW", font=font(22, True), fill=MUTED)
    native = Image.open(frame).convert("RGB")
    native.thumbnail((795, 800), Image.Resampling.LANCZOS)
    image.paste(native, (785 + (795-native.width)//2, (900-native.height)//2))
    image.save(MEDIA / "TwoMinutes-cover.jpg", quality=94)


if __name__ == "__main__":
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
        rendered = list(pool.map(render_scene, enumerate(timeline["scenes"])))
    listing = OUT / "all-scenes.txt"
    listing.write_text("".join(f"file '{p.name}'\n" for p in rendered))
    caption_path = make_captions()
    # Paths with spaces are passed as arguments, never through a shell.
    escaped = str(caption_path).replace("\\", "\\\\").replace(":", "\\:").replace("'", "\\'")
    final = MEDIA / "TwoMinutes-demo.mp4"
    run(["-f", "concat", "-safe", "0", "-i", str(listing), "-i", str(MEDIA / "narration.wav"),
         "-vf", f"subtitles=filename='{escaped}'", "-af", "loudnorm=I=-16:TP=-1.5:LRA=9",
         "-map", "0:v:0", "-map", "1:a:0", "-c:v", "libx264", "-threads", "6", "-preset", "fast", "-crf", "19",
         "-c:a", "aac", "-b:a", "192k", "-ar", "48000", "-pix_fmt", "yuv420p", "-movflags", "+faststart",
         "-t", str(timeline["scenes"][-1]["end"]), "-y", str(final)])
    cover()
    (MEDIA / "edit-plan.json").write_text(json.dumps({"resolution":[WIDTH, HEIGHT],"fps":FPS,"edits":EDITS,"input":"Lens Studio native Preview recordings","captionSource":"sentence-aligned synthesis timings","nativeAudio":"omitted; narration only"}, indent=2) + "\n")
    print(final, flush=True)
